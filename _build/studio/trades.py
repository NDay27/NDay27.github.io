def pick_kind(lead):
    """Choose a profile from the lead's own trade label, categories and services."""
    lab = (lead.get("trade_label") or "").lower()
    for k, key in KEYMAP:
        if k in lab:
            return key
    code = (lead.get("trade_code") or "").lower()
    if code in CODEMAP:
        return CODEMAP[code]
    txt = " ".join([" ".join(lead.get("yp_cats") or []), " ".join(lead.get("services") or [])]).lower()
    for k, key in KEYMAP:
        if k in txt:
            return key
    return "repair"
